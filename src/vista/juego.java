    //bloquear los botones 
    public void terminarPartida(){
        botonPedir.setEnabled(false);
        botonPlantarse.setEnabled(false);
        botonVolverMenu.setEnabled(false);
    }
    public void empezarPartida(){
        botonPedir.setEnabled(true);
        botonPlantarse.setEnabled(true);
        botonVolverMenu.setEnabled(true);
        botonEmpezarPartida.setVisible(false);   // ya empezó: el botón desaparece
    }

    // Mesa al entrar: solo se puede empezar o volver al menú
    public void esperarInicio(){
        botonPedir.setEnabled(false);
        botonPlantarse.setEnabled(false);
    }
