    // Métodos para que el controlador cargue el ranking
    // Borra todas las filas de la tabla
    public void limpiarTabla() {
        modeloTabla.setRowCount(0);
    }

    // Agrega una fila al final de la tabla
    public void agregarFila(int puesto, String nombre, int ganadas) {
        modeloTabla.addRow(new Object[]{puesto, nombre, ganadas});
    }

